-- "RecipeIngredients"."id" was defined as a bare INTEGER PRIMARY KEY with no way to
-- generate new ids (no sequence/identity), which blocked ever inserting a row through
-- PostgREST without the caller manually picking one. Table has no existing rows yet,
-- so this is safe to apply without a data backfill.
ALTER TABLE "RecipeIngredients"
    ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY;

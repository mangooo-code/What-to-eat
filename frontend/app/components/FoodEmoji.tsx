function findKeywordEmoji(name: string, rules: EmojiKeywordRule[], minimumKeywordLength = 1): string | null {
  const matches = rules.flatMap((rule) =>
    rule.keywords
      .filter((keyword) => keyword.length >= minimumKeywordLength && name.includes(keyword))
      .map((keyword) => ({ ...rule, keyword })),
  );
  matches.sort((a, b) => b.keyword.length - a.keyword.length || b.priority - a.priority);
  return matches[0]?.emoji ?? null;
}

function emojiForFood(name: string): string {
  const normalizedName = name.trim();
  const exactMatch = emojiByName[normalizedName];
  if (exactMatch) return exactMatch;
  const specificKeywordMatch = findKeywordEmoji(normalizedName, emojiBySpecificKeyword, 2);
  if (specificKeywordMatch) return specificKeywordMatch;
  return findKeywordEmoji(normalizedName, emojiByCategory) ?? "🍽️";
}

export function FoodEmoji({ name, className = "food-emoji" }: { name: string; className?: string }) {
  return <span className={className} role="img" aria-label={name}>{emojiForFood(name)}</span>;
}
